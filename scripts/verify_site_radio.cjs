 console.log(JSON.stringify({songs:84,continuousAcross:['homepage','brands','api','privacy','back','forward'],sameAudioNode:state.same,requestsBeforeSongChange:1,collapse:'passed',volume:'passed',pause:'passed',songSelection:'passed'}));
