const fs=require('node:fs');
const assert=require('node:assert/strict');
const {chromium}=require(process.argv[2]+'/playwright');
function testAudio(){
  const rate=8000,seconds=60,length=rate*seconds*2,buffer=Buffer.alloc(44+length);
  buffer.write('RIFF',0);buffer.writeUInt32LE(36+length,4);buffer.write('WAVEfmt ',8);buffer.writeUInt32LE(16,16);buffer.writeUInt16LE(1,20);buffer.writeUInt16LE(1,22);buffer.writeUInt32LE(rate,24);buffer.writeUInt32LE(rate*2,28);buffer.writeUInt16LE(2,32);buffer.writeUInt16LE(16,34);buffer.write('data',36);buffer.writeUInt32LE(length,40);
  return buffer;
}
